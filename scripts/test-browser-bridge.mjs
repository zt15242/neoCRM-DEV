import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const dir = await mkdtemp(path.join(os.tmpdir(), 'neo-browser-test-'));
try {
  const outfile = path.join(dir, 'bridge.cjs');
  await build({ entryPoints: ['electron/services/browserBridge.ts'], outfile, platform: 'node', format: 'cjs', bundle: true, logLevel: 'silent' });
  const { BrowserBridge } = await import(pathToFileURL(outfile).href);
  const bridge = new BrowserBridge();
  const { port, token } = await bridge.start();
  const base = `http://127.0.0.1:${port}`;
  const headers = { Authorization: `Bearer ${token}` };
  assert.equal((await fetch(`${base}/next`)).status, 403);
  assert.equal((await fetch(`${base}/next`, { headers: { ...headers, Origin: 'https://attacker.test' } })).status, 403);
  assert.equal((await fetch(`${base}/next`, { headers })).status, 200);
  assert.equal(bridge.status().connected, true);
  const pending = bridge.execute('tabs', {});
  const command = (await (await fetch(`${base}/next`, { headers })).json()).command;
  assert.equal(command.action, 'tabs');
  assert.equal((await fetch(`${base}/result`, { method: 'POST', headers, body: JSON.stringify({ id: command.id, ok: true, result: [{ id: 4 }] }) })).status, 200);
  assert.deepEqual(await pending, [{ id: 4 }]);
  const controller = new AbortController();
  const cancelled = bridge.execute('snapshot', {}, controller.signal);
  controller.abort();
  await assert.rejects(cancelled, /取消/);
  assert.equal((await (await fetch(`${base}/next`, { headers })).json()).command, null);
  const stopping = bridge.execute('tabs', {});
  bridge.stop();
  await assert.rejects(stopping, /关闭/);
  assert.equal(bridge.status().listening, false);
  const second = await bridge.start();
  assert.notEqual(second.token, token);
  bridge.stop();
  const persisted = new BrowserBridge();
  persisted.configurePersistence(path.join(dir, 'pairing.json'));
  const once = await persisted.start();
  assert.equal(once.port, 39877);
  persisted.stop(false);
  const restarted = new BrowserBridge();
  restarted.configurePersistence(path.join(dir, 'pairing.json'));
  assert.equal(restarted.autoStartEnabled, true);
  const again = await restarted.start();
  assert.deepEqual(again, once);
  restarted.stop();
  const disabled = new BrowserBridge();
  disabled.configurePersistence(path.join(dir, 'pairing.json'));
  assert.equal(disabled.autoStartEnabled, false);
  const reopened = await disabled.start();
  assert.deepEqual(reopened, once);
  disabled.stop();
  console.log('Browser bridge: authentication, origin checks, commands, cancellation and shutdown passed');
} finally { await rm(dir, { recursive: true, force: true }); }
